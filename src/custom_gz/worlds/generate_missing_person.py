#!/usr/bin/env python3
"""Generate the missing_person Gazebo model for the search-and-rescue world.

A life-size casualty lying on the ground in a hi-vis ORANGE coverall (the
detection target of camera_processor.PERSON_HSV_*), with skin-tone head/hands
and dark boots for realism. Position and heading are random but seeded, so
runs are repeatable; ground truth goes to ground_truth.json next to the model.

Placement uses world (0,0) = field GPS origin (the JSON FDM convention — see
CLAUDE.md), so swarm_drone_sar.sdf includes the model at pose 0 0 0 and the
ground-truth lat/lon is directly comparable with the drones' GPS. The drone
spawn cluster (world ~(45..60, 50)) is excluded so the person is never found
trivially at takeoff.

    python3 src/custom_gz/worlds/generate_missing_person.py --seed 7
"""
import argparse
import json
import math
import os
import random

# Must match LAT_BASE/LON_BASE in src/scripts/start_drone_container.sh
LAT_BASE = 40.072842
LON_BASE = -105.230575
METERS_PER_DEG_LAT = 111111.0

SPAWN_XY = (52.5, 50.0)      # centre of the drone spawn cluster
SPAWN_EXCLUSION_M = 20.0

# Hi-vis coverall. Emissive carries the colour; lit ambient/diffuse are kept
# weak (EMISSIVE_BASE_SCALE). With full-strength diffuse on top of emissive,
# red clips at 255 under the sun while green keeps rising, and the render
# comes out YELLOW (measured OpenCV H ~28) - outside the detector's H 0-14
# band. Colours are LINEAR and the camera outputs sRGB, so green must be tiny:
# linear 0.3 renders ~150/255 (amber, measured H ~20); linear 0.06 renders
# ~69/255, i.e. hi-vis orange at H ~8-9.
ORANGE = "1 0.06 0 1"
EMISSIVE_BASE_SCALE = 0.25
SKIN = "0.80 0.62 0.48 1"
BOOTS = "0.12 0.10 0.08 1"

# (name, x_along_body, y_across, z, size_xyz | radius, colour, emissive)
# Body frame: +x from feet to head, lying face-up, centred on the hips.
PARTS = [
    ("torso", 0.30, 0.0, 0.13, ("box", "0.62 0.42 0.22"), ORANGE, True),
    ("legs", -0.45, 0.0, 0.10, ("box", "0.88 0.34 0.17"), ORANGE, True),
    ("arm_l", 0.30, 0.29, 0.09, ("box", "0.58 0.12 0.11"), ORANGE, True),
    ("arm_r", 0.30, -0.29, 0.09, ("box", "0.58 0.12 0.11"), ORANGE, True),
    ("head", 0.74, 0.0, 0.11, ("sphere", "0.11"), SKIN, False),
    ("boots", -0.95, 0.0, 0.08, ("box", "0.14 0.30 0.15"), BOOTS, False),
]


def world_to_latlon(x, y):
    """World x = east, y = north (ENU) around the field GPS origin."""
    lat = LAT_BASE + y / METERS_PER_DEG_LAT
    lon = LON_BASE + x / (METERS_PER_DEG_LAT * math.cos(math.radians(LAT_BASE)))
    return lat, lon


def place_person(seed, area):
    rng = random.Random(seed)
    half = area / 2.0 - 5.0          # keep the whole figure inside the area
    while True:
        x = round(rng.uniform(-half, half), 3)
        y = round(rng.uniform(-half, half), 3)
        if math.hypot(x - SPAWN_XY[0], y - SPAWN_XY[1]) >= SPAWN_EXCLUSION_M:
            break
    yaw = round(rng.uniform(-math.pi, math.pi), 4)
    lat, lon = world_to_latlon(x, y)
    return {"x": x, "y": y, "yaw": yaw,
            "lat": round(lat, 8), "lon": round(lon, 8)}


def _link(name, px, py, pz, geom, colour, emissive):
    kind, size = geom
    geom_xml = (f"<box><size>{size}</size></box>" if kind == "box"
                else f"<sphere><radius>{size}</radius></sphere>")
    emis = colour if emissive else "0 0 0 1"
    if emissive:  # see ORANGE: weak lit colour so the hue does not clip
        r, g, b, alpha = (float(v) for v in colour.split())
        k = EMISSIVE_BASE_SCALE
        colour = f"{r * k:g} {g * k:g} {b * k:g} {alpha:g}"
    return f"""    <link name="{name}">
      <pose>{px} {py} {pz} 0 0 0</pose>
      <visual name="visual">
        <geometry>{geom_xml}</geometry>
        <material>
          <ambient>{colour}</ambient>
          <diffuse>{colour}</diffuse>
          <emissive>{emis}</emissive>
        </material>
      </visual>
    </link>
"""


def model_sdf(person):
    links = "".join(_link(*p) for p in PARTS)
    return f"""<?xml version="1.0"?>
<sdf version="1.9">
  <!-- GENERATED by src/custom_gz/worlds/generate_missing_person.py - do not
       hand-edit. Casualty in a hi-vis orange coverall, lying face-up.
       Visual-only (no collision). Ground truth: ground_truth.json. -->
  <model name="missing_person">
    <static>true</static>
    <pose>{person['x']} {person['y']} 0.1 0 0 {person['yaw']}</pose>
{links}  </model>
</sdf>
"""


MODEL_CONFIG = """<?xml version="1.0"?>
<model>
  <name>missing_person</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <description>
    Missing person (hi-vis orange coverall) for the search-and-rescue world.
    Generated by generate_missing_person.py.
  </description>
</model>
"""


def write_model(person, out_dir, meta):
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "model.sdf"), "w") as f:
        f.write(model_sdf(person))
    with open(os.path.join(out_dir, "model.config"), "w") as f:
        f.write(MODEL_CONFIG)
    with open(os.path.join(out_dir, "ground_truth.json"), "w") as f:
        json.dump({**meta, "person": person}, f, indent=2)


def main():
    default_out = os.path.normpath(os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "..", "models",
        "missing_person"))
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--seed", type=int, default=7)
    p.add_argument("--area", type=float, default=120.0,
                   help="side of the square search area centred on the "
                        "field origin (m); must match sar_mission.launch.py")
    p.add_argument("--out", default=default_out)
    args = p.parse_args()
    person = place_person(args.seed, args.area)
    write_model(person, args.out, {"seed": args.seed, "area": args.area})
    print(f"missing person at world ({person['x']}, {person['y']}) "
          f"= {person['lat']}, {person['lon']} -> {args.out}")


if __name__ == "__main__":
    main()
